import { getAllContent, getContentBySlug } from './content-core';
import {
  tapestrySchema,
  validateFrontmatter,
  FrontmatterValidationError,
} from './content-schemas';
import fs from 'fs';
import path from 'path';

// Define the possible status values as an enum
export type TapestryStatus =
  | 'Not Started'
  | 'Designed'
  | 'In Production'
  | 'Finished';

// Define the structure for timeline events
export interface TimelineEvent {
  date: string;
  title: string;
  description: string;
}

// Define the structure for resources
export interface TapestryResource {
  title: string;
  description: string;
  kind: string;
  url: string;
}

// Validate that a status is one of the allowed values
export function isValidStatus(status: string): status is TapestryStatus {
  return ['Not Started', 'Designed', 'In Production', 'Finished'].includes(
    status,
  );
}

export interface TapestryEntry {
  slug: string;
  title: string;
  summary: string;
  thumbnail: string;
  background_color: string;
  content: string;
  imagePath?: string;
  artworkPath?: string;
  audioPath?: string;
  audioDescription?: string;
  colony?: string | null;
  status: TapestryStatus;
  timelineEvents?: TimelineEvent[];
  resources?: TapestryResource[];
}

