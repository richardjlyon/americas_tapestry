#!/usr/bin/env node

/**
 * Regenerate the deployment-exclusion block in .vercelignore.
 *
 * WHY THIS EXISTS
 *
 * Images are served from Cloudflare R2 via src/lib/image-manifest.json, but the
 * originals stay committed under public/images — which means Vercel also serves
 * them at stable origin URLs. Crawlers keep fetching those URLs long after the
 * pages that referenced them changed, and that traffic (not human visitors) blew
 * the free-tier transfer cap. See VERCEL_USAGE_INVESTIGATION.md, 6 July 2026.
 *
 * The fix is to keep the files in git and on disk, and exclude them from the
 * DEPLOYMENT. Nothing is deleted, so a wrong answer here costs a redeploy rather
 * than a file.
 *
 * WHY NOT JUST DELETE THEM
 *
 * Two attempts on 2026-09-01 derived a "safe to delete" set — first from crawled
 * HTML, then from content markdown plus src/ plus the crawl — and both were
 * confidently wrong. Next.js builds asset paths at RENDER time from a slug plus
 * a bare filename (src/lib/exhibitions.ts, tapestries.ts, sponsors.ts,
 * shop-products.ts, content-core.ts), so a required path can exist in no file
 * anywhere. Static analysis cannot see it. Do not try again.
 *
 * HOW THIS DECIDES
 *
 * A file is excluded only if BOTH hold:
 *   1. It has an R2 variant in image-manifest.json, so the CDN can serve it.
 *   2. The rendered site never requests it at its origin path.
 *
 * Condition 2 is measured, not reasoned: pass a file of origin paths captured by
 * actually crawling a production build (see --refs). Without that file this
 * script refuses to run, because guessing is exactly the failure mode above.
 *
 * USAGE
 *
 *   # 1. build and serve, then crawl every sitemap URL collecting /images/ refs
 *   # 2. then:
 *   node scripts/generate-vercelignore.mjs --refs=/tmp/rendered-image-refs.txt
 *   node scripts/generate-vercelignore.mjs --refs=... --check   # CI: no writes
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC_DIR = path.join(ROOT, 'public');
const MANIFEST = path.join(ROOT, 'src', 'lib', 'image-manifest.json');
const IGNORE_FILE = path.join(ROOT, '.vercelignore');

const BEGIN = '# BEGIN r2-duplicates (generated by scripts/generate-vercelignore.mjs — do not edit by hand)';
const END = '# END r2-duplicates';

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

function main() {
  const refsArg = process.argv.find(a => a.startsWith('--refs='));
  const check = process.argv.includes('--check');

  if (!refsArg) {
    console.error('Refusing to run without --refs=<file>.\n');
    console.error('That file must list the /images/... origin paths a RENDERED');
    console.error('production build actually requests, captured by crawling it.');
    console.error('Deriving the set any other way has failed twice — see the');
    console.error('header of this script and Plane TAPSTRY-9.');
    process.exit(2);
  }

  const refsPath = refsArg.slice('--refs='.length);
  if (!fs.existsSync(refsPath)) {
    console.error(`--refs file not found: ${refsPath}`);
    process.exit(2);
  }

  const referenced = new Set(
    fs.readFileSync(refsPath, 'utf8')
      .split('\n')
      .map(s => s.trim())
      .filter(s => s.startsWith('/images/')),
  );

  if (referenced.size === 0) {
    console.error(`--refs file contained no /images/ paths: ${refsPath}`);
    console.error('An empty reference set would exclude everything. Refusing.');
    process.exit(2);
  }

  const manifest = new Set(Object.keys(JSON.parse(fs.readFileSync(MANIFEST, 'utf8'))));

  const excluded = [];
  let excludedBytes = 0;
  let keptBytes = 0;

  for (const file of walk(path.join(PUBLIC_DIR, 'images'))) {
    const web = '/' + path.relative(PUBLIC_DIR, file).split(path.sep).join('/');
    const size = fs.statSync(file).size;
    if (manifest.has(web) && !referenced.has(web)) {
      excluded.push(web);
      excludedBytes += size;
    } else {
      keptBytes += size;
    }
  }

  excluded.sort();

  const block = [
    BEGIN,
    `# ${excluded.length} files, ${(excludedBytes / 1e6).toFixed(1)}MB. Every one has an R2 variant`,
    '# and is not requested at its origin path by any rendered page. The files stay',
    '# in git and on disk; they are simply not uploaded to Vercel.',
    ...excluded.map(w => `public${w}`),
    END,
  ].join('\n');

  const current = fs.existsSync(IGNORE_FILE) ? fs.readFileSync(IGNORE_FILE, 'utf8') : '';
  const hasBlock = current.includes(BEGIN);
  const next = hasBlock
    ? current.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}`), block)
    : `${current.trimEnd()}\n\n${block}\n`;

  console.log(`Excluded from deployment: ${excluded.length} files, ${(excludedBytes / 1e6).toFixed(1)}MB`);
  console.log(`Still deployed:           ${(keptBytes / 1e6).toFixed(1)}MB`);

  if (check) {
    if (next !== current) {
      console.error('\n.vercelignore is out of date — re-run without --check.');
      process.exit(1);
    }
    console.log('.vercelignore is up to date.');
    return;
  }

  fs.writeFileSync(IGNORE_FILE, next);
  console.log(`\nWrote ${path.relative(ROOT, IGNORE_FILE)}`);
}

main();
